"""openplay.moves: the moves catalogue for phone buttons (data in openplay/moves.json).

    catalogue() -> [{name, title, emoji, duration_s, blurb, tags}]   only moves that validate
    load(name)  -> the playable dict (playables/<name>.json); KeyError if not catalogued
    match(text) -> closest catalogued move for free text, or None ("say hi to everyone" -> "wave-hello")

Nothing here moves the arm. Playables are validated with armctl.playable.validate (the same
gate the daemon applies, with the playable's own "caps" preset). New moves are generated by
openplay/tools/make_moves.py.
"""
from __future__ import annotations

import copy
import difflib
import json
import logging
import re
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:  # allow `python openplay/moves.py` and rootdir-less imports
    sys.path.insert(0, str(REPO))

from armctl import playable as P  # noqa: E402

log = logging.getLogger("openplay.moves")

MOVES_JSON = Path(__file__).resolve().parent / "moves.json"
FIELDS = ("name", "title", "emoji", "duration_s", "blurb", "tags")

_cache: dict[str, Any] = {"key": None, "moves": []}


def _entries() -> list[dict]:
    data = json.loads(MOVES_JSON.read_text())
    if not isinstance(data, list):
        raise ValueError(f"{MOVES_JSON} must hold a JSON list")
    return data


def _key() -> tuple:
    files = [MOVES_JSON] + sorted(P.PLAYABLES_DIR.glob("*.json"))
    return tuple((str(f), f.stat().st_mtime_ns) for f in files if f.exists())


def catalogue() -> list[dict]:
    """Catalogued moves that validate, in moves.json order, each with ``duration_s``.

    Moves that are missing, unreadable or rejected by armctl.playable.validate are dropped
    and logged (warning) with the reason. Cached until moves.json or a playable changes.
    """
    key = _key()
    if _cache["key"] == key:
        return copy.deepcopy(_cache["moves"])
    out = []
    for e in _entries():
        name = e.get("name") if isinstance(e, dict) else None
        if not isinstance(name, str) or not P.NAME_RE.match(name):
            log.warning("moves.json: skipping entry with bad name: %r", e)
            continue
        try:
            p = P.load(name)
        except Exception as ex:  # missing file, bad JSON
            log.warning("move %s dropped: can't load playables/%s.json (%s)", name, name, ex)
            continue
        try:
            r = P.validate(p)
        except Exception as ex:
            log.warning("move %s dropped: validate raised %s", name, ex)
            continue
        if not r["ok"]:
            why = "; ".join(v["msg"] for v in r["violations"][:3])
            log.warning("move %s dropped: does not validate: %s", name, why)
            continue
        out.append({"name": name, "title": e.get("title") or name.replace("-", " ").capitalize(),
                    "emoji": e.get("emoji", ""), "duration_s": round(float(r["duration"]), 1),
                    "blurb": e.get("blurb", ""), "tags": list(e.get("tags", []))})
    _cache["key"], _cache["moves"] = key, out
    return copy.deepcopy(out)


def names() -> list[str]:
    return [m["name"] for m in catalogue()]


def load(name: str) -> dict:
    """The playable for a catalogued move. KeyError for anything not in the catalogue."""
    if name not in names():
        raise KeyError(f"unknown move {name!r}")
    return P.load(name)


# --- free-text matching ------------------------------------------------------------------

STOP = {"a", "an", "the", "to", "do", "does", "me", "us", "you", "your", "my", "some", "please",
        "pls", "can", "could", "would", "will", "go", "make", "it", "its", "for", "of", "at",
        "on", "in", "and", "or", "with", "just", "now", "again", "bit", "little", "kind",
        "sort", "like", "be", "is", "are", "i", "we", "them", "this", "that", "arm", "say",
        "show", "give", "let", "lets", "want", "everyone", "everybody", "all", "people", "kids",
        "children", "guys", "folks", "really", "very", "so", "one", "move", "how", "what"}
# "kids" and "everyone" are audience words, not moves ("wave at the kids" is a wave).
# Weak words count for little on their own: people call the arm "robot" all the time.
WEAK = {"robot": 0.4, "music": 0.5, "fun": 0.5, "hand": 0.5, "pop": 0.6, "beat": 0.6, "look": 0.8}
_SYN = {"hello": "hello", "hullo": "hello", "hallo": "hello", "hii": "hi", "hiii": "hi",
        "thx": "thanks", "ty": "thanks", "yay": "yay", "yess": "yes", "nooo": "no", "noo": "no",
        "zzz": "sleep", "dancing": "dance", "danc": "dance"}


def _tokens(text: str) -> list[str]:
    t = text.lower().replace("'", "").replace("’", "")
    return re.findall(r"[a-z0-9]+", t)


def _stem(w: str) -> str:
    w = _SYN.get(w, w)
    for suf in ("ing", "ed", "es", "s"):
        if len(w) > len(suf) + 2 and w.endswith(suf):
            w = w[: -len(suf)]
            if len(w) > 3 and w[-1] == w[-2] and w[-1] not in "aeiouls":
                w = w[:-1]  # clapping -> clap, nodding -> nod (but not "dress", "roll")
            break
    return w.rstrip("e") if len(w) > 3 else w


def _index(moves: list[dict]) -> list[tuple[str, dict[str, float]]]:
    """Per move: {stemmed keyword: weight}. Name and title words weigh most."""
    idx = []
    for m in moves:
        kw: dict[str, float] = {}
        def put(w: str, weight: float) -> None:
            k = _stem(w)
            kw[k] = max(kw.get(k, 0.0), min(weight, WEAK.get(w, weight)))

        for t in m["tags"]:
            for w in _tokens(t):
                put(w, 1.0)
            put("".join(_tokens(t)), 1.0)
        for w in _tokens(m["name"]) + _tokens(m["title"]):
            if w not in STOP:
                put(w, 1.2)
        idx.append((m["name"], kw))
    return idx


def _score_token(tok: str, kw: dict[str, float]) -> float:
    if tok in kw:
        return kw[tok]
    if len(tok) >= 5:  # typo tolerance only for longer words ("celebrat", "peekabo")
        best = difflib.get_close_matches(tok, [k for k in kw if len(k) >= 4], n=1, cutoff=0.8)
        if best:
            return 0.7 * kw[best[0]]
    return 0.0


def match(text: str) -> str | None:
    """Closest catalogued move for free text, keyword based; None if nothing fits.

    "say hi to everyone" -> "wave-hello", "do a little dance" -> "happy-dance",
    "high five!" -> "high-five-offer", "what's the weather" -> None.
    """
    if not isinstance(text, str) or not text.strip():
        return None
    moves = catalogue()
    if not moves:
        return None
    raw = _tokens(text)
    # an exact move name or title in the text wins outright
    flat = " " + " ".join(raw) + " "
    for m in moves:
        for phrase in (m["name"], m["title"]):
            words = _tokens(phrase)
            if (len(words) > 1 or len(words[0]) > 4) and f" {' '.join(words)} " in flat:
                return m["name"]
    words = [w for w in raw if w not in STOP]
    toks = [_stem(w) for w in words]
    toks += [_stem(a + b) for a, b in zip(words, words[1:])]  # "high five" -> "highfive"
    if not toks:
        return None
    best, best_score = None, 0.0
    for name, kw in _index(moves):
        s = sum(_score_token(t, kw) for t in toks)
        if s > best_score + 1e-9:  # ties go to the earlier (more general) move in moves.json
            best, best_score = name, s
    return best if best_score >= 0.7 else None


if __name__ == "__main__":  # .venv/bin/python openplay/moves.py ["free text" ...]
    logging.basicConfig(level=logging.INFO)
    if len(sys.argv) > 1:
        for q in sys.argv[1:]:
            print(f"{q!r} -> {match(q)}")
    else:
        for m in catalogue():
            print(f"{m['emoji']} {m['name']:16s} {m['duration_s']:5.1f}s  {m['blurb']}")
